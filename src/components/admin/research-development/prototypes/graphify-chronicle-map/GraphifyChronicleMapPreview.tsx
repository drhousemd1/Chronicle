import { useState } from "react";
import { Database, FolderTree, GitFork, LayoutGrid } from "lucide-react";

import {
  ChronicleDarkShell,
  ChronicleSurfaceButton,
} from "@/components/chronicle/ChronicleDarkUi";
import { cn } from "@/lib/utils";

const GRAPHIFY_ARTIFACT_ROOT = "/__rnd-repository/generated/graphify-chronicle-map";

const VIEW_OPTIONS = [
  {
    id: "chronicle-areas",
    label: "Chronicle Areas",
    title: "Chronicle product areas organized over Graphify communities",
    src: `${GRAPHIFY_ARTIFACT_ROOT}/chronicle-areas.html`,
    Icon: LayoutGrid,
  },
  {
    id: "tree",
    label: "Repository Tree",
    title: "Chronicle repository tree generated by Graphify",
    src: `${GRAPHIFY_ARTIFACT_ROOT}/graph-tree.html`,
    Icon: FolderTree,
  },
  {
    id: "dependencies",
    label: "Dependency Graph",
    title: "Chronicle full dependency graph generated by Graphify",
    src: `${GRAPHIFY_ARTIFACT_ROOT}/graph-full.html`,
    Icon: GitFork,
  },
  {
    id: "communities",
    label: "Community Overview",
    title: "Chronicle aggregated architecture communities generated by Graphify",
    src: `${GRAPHIFY_ARTIFACT_ROOT}/graph-communities.html`,
    Icon: Database,
  },
] as const;

type ViewId = (typeof VIEW_OPTIONS)[number]["id"];

export function GraphifyChronicleMapPreview() {
  const [selectedView, setSelectedView] = useState<ViewId>("chronicle-areas");
  const activeView = VIEW_OPTIONS.find((view) => view.id === selectedView) ?? VIEW_OPTIONS[0];

  return (
    <ChronicleDarkShell className="w-full min-w-0 border border-white/[0.08]">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-white/[0.08] bg-[#1c1c1f] px-4 py-3">
        <div
          role="group"
          aria-label="Graphify map view"
          className="flex flex-wrap items-center gap-2"
        >
          {VIEW_OPTIONS.map(({ id, label, Icon }) => {
            const selected = id === selectedView;
            return (
              <ChronicleSurfaceButton
                key={id}
                aria-pressed={selected}
                onClick={() => setSelectedView(id)}
                className={cn(
                  "gap-2 px-4",
                  selected && "bg-[#3b82f6] hover:bg-[#3b82f6]",
                )}
              >
                <Icon className="h-4 w-4" aria-hidden="true" />
                {label}
              </ChronicleSurfaceButton>
            );
          })}
        </div>
        <p className="text-[11px] font-semibold text-[#a1a1aa]">
          Static local scan · no live Supabase connection
        </p>
      </div>

      <div className="min-h-[680px] bg-[#0d0e12]">
        <iframe
          key={activeView.id}
          title={activeView.title}
          src={activeView.src}
          sandbox="allow-scripts"
          referrerPolicy="no-referrer"
          className="block h-[760px] w-full border-0 bg-[#0d0e12]"
          data-testid="graphify-chronicle-frame"
        />
      </div>
    </ChronicleDarkShell>
  );
}
